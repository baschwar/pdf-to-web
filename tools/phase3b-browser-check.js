/* Disposable local browser verification. Pass a bootstrap URL and fixture project directory. */
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const { chromium } = require('./wordpress-roundtrip/node_modules/playwright-core');
const url = process.argv[2];
const project = path.resolve(process.argv[3]);
const evidence = path.resolve('build/phase3b');
async function main() {
  const browser = await chromium.launch({executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
  const report = {date: '2026-09-30', browser: browser.version(), checks: {}, errors: []};
  page.on('pageerror', error => report.errors.push(error.message));
  const change = async (locator, keyboard = false) => {
    await locator.focus();
    await Promise.all([page.waitForEvent('framenavigated'), keyboard ? page.keyboard.press('Enter') : locator.click()]);
    await page.waitForLoadState('domcontentloaded');
  };
  try {
    await page.goto(url);
    await page.getByRole('link', {name: 'Output Pages', exact: true}).click();
    await page.waitForURL('**/output-pages');
    const read = () => JSON.parse(fs.readFileSync(path.join(project, 'review/current.json')));
    let current = read();
    assert.equal(current.blocks[2].content, 'Saved older-project edit');
    assert.equal(current.accessibility_review.decisions['diagnostic:example:document'].note, 'Preserved');
    report.checks.legacyEditsAndDecisionsSurvive = true;
    await page.getByText('Grouping suggestions', {exact: true}).click();
    assert((await page.locator('details').innerText()).includes('Policy'));
    assert.equal(read().output_pages.pages.length, 1);
    await change(page.getByRole('button', {name: 'Apply replacement arrangement'}), true);
    assert.equal(read().output_pages.pages.length, 2);
    report.checks.suggestionsInspectedAndAppliedByKeyboard = true;
    assert.equal(await page.evaluate(() => document.activeElement.id), 'page-editor');
    report.checks.focusAfterApply = true;
    const initial = read().output_pages.pages.map(p => p.id);
    await change(page.locator('[data-page-action="split"][data-block-id="p2"]'), true);
    assert.equal(read().output_pages.pages.length, 3);
    await change(page.getByRole('button', {name: 'Undo last action', exact: true}), true);
    assert.deepEqual(read().output_pages.pages.map(p => p.id), initial);
    await change(page.getByRole('button', {name: 'Merge pages', exact: true}), true);
    assert.equal(read().output_pages.pages.length, 1);
    await change(page.getByRole('button', {name: 'Undo last action', exact: true}), true);
    assert.deepEqual(read().output_pages.pages.map(p => p.id), initial);
    report.checks.splitMergeAndUndo = true;
    await change(page.getByRole('button', {name: 'Create page', exact: true}), true);
    assert((await page.locator('main').innerText()).includes('empty page'));
    await change(page.locator('[data-page-action="assign"][data-block-id="p2"]'), true);
    assert.equal(read().output_pages.pages[2].block_ids[0], 'p2');
    await change(page.getByRole('button', {name: 'Undo last action', exact: true}), true);
    await change(page.getByRole('button', {name: 'Undo last action', exact: true}), true);
    report.checks.createAssignAndUndo = true;
    await page.locator(`aside a[href*="${initial[1]}"]`).click();
    await page.locator('#output-page-metadata [name="title"]').fill('Policy & procedures');
    await page.locator('#output-page-metadata [name="slug"]').fill('policy-procedures');
    await page.locator('#output-page-metadata [name="parent"]').selectOption(initial[0]);
    await page.locator('#output-page-metadata [name="navigation_order"]').fill('7');
    await change(page.getByRole('button', {name: 'Save page', exact: true}), true);
    assert.equal(read().output_pages.pages[1].parent, initial[0]);
    await page.locator('#output-page-metadata [name="type"]').selectOption('post');
    await change(page.getByRole('button', {name: 'Save page', exact: true}), true);
    assert((await page.locator('main').innerText()).includes('Articles have no parent'));
    await page.locator('#output-page-metadata [name="parent"]').selectOption('');
    await change(page.getByRole('button', {name: 'Save page', exact: true}), true);
    assert.equal(read().output_pages.pages[1].type, 'post');
    await page.locator('#output-page-metadata [name="type"]').selectOption('page');
    await page.locator('#output-page-metadata [name="parent"]').selectOption(initial[0]);
    await change(page.getByRole('button', {name: 'Save page', exact: true}), true);
    report.checks.metadataTypesHierarchyOrder = true;
    await change(page.getByRole('button', {name: 'Mark page reviewed', exact: true}), true);
    assert.equal(read().output_pages.pages[1].approval.status, 'reviewed');
    await page.locator('#output-page-metadata [name="slug"]').fill('policy-final');
    await change(page.getByRole('button', {name: 'Save page', exact: true}), true);
    assert.equal(read().output_pages.pages[1].approval.status, 'needs_review');
    report.checks.approvalInvalidation = true;
    await page.getByRole('link', {name: 'Projects', exact: true}).click();
    await change(page.locator('.open-project').first(), true);
    await page.getByRole('link', {name: 'Output Pages', exact: true}).click();
    await page.locator(`aside a[href*="${initial[1]}"]`).click();
    assert.equal(await page.locator('#output-page-metadata [name="slug"]').inputValue(), 'policy-final');
    report.checks.saveAndReopen = true;
    await page.getByRole('button', {name: 'Preview page', exact: true}).click();
    const frame = page.frameLocator('#output-page-frame');
    await frame.getByRole('heading', {name: 'Policy & procedures', exact: true}).waitFor();
    await frame.getByRole('link', {name: 'Welcome', exact: true}).click();
    await frame.getByRole('heading', {name: 'Handbook', exact: true}).waitFor();
    report.checks.crossPagePreviewLink = true;
    await page.getByRole('button', {name: 'WordPress Preview', exact: true}).click();
    await frame.getByRole('heading', {name: 'Policy & procedures', exact: true}).waitFor();
    report.checks.wordPressPreview = true;
    await page.getByRole('button', {name: 'Export page', exact: true}).click();
    await page.locator('#output-page-message a').first().waitFor();
    assert(fs.existsSync(path.join(project, 'output/page-2/manifest.json')));
    await page.getByRole('button', {name: 'Export complete package', exact: true}).click();
    await page.locator('#output-page-message a').filter({hasText: 'output/pages.zip'}).waitFor();
    const manifest = JSON.parse(fs.readFileSync(path.join(project, 'output/pages/manifest.json')));
    assert.equal(manifest.pages.length, 2);
    assert.equal(manifest.pages[1].parent, initial[0]);
    assert.equal(manifest.pages[1].navigation_order, 7);
    assert.equal(manifest.pages[1].slug, 'policy-final');
    assert.equal(manifest.pages.flatMap(p => p.block_ids).length, read().blocks.length);
    assert(manifest.pages.every(p => p.files.html && p.files.gutenberg && p.files.wxr));
    report.checks.individualAndPackageExport = true;
    report.checks.manifestMatchesArrangement = true;
    assert.equal(report.errors.length, 0);
    const names = await page.locator('button, input, select, textarea, a[href]').evaluateAll(nodes => nodes.filter(n => n.getBoundingClientRect().width > 0 && n.getBoundingClientRect().height > 0).map(n => n.getAttribute('aria-label') || n.labels?.[0]?.innerText.trim() || n.innerText.trim() || n.title));
    assert(names.every(Boolean));
    report.checks.visibleControlsNamed = true;
    report.checks.liveAnnouncement = await page.locator('#output-page-message[role="status"][aria-live="polite"]').count() === 1;
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({path: path.join(evidence, 'output-pages-desktop.png'), fullPage: true});
    await page.setViewportSize({width: 700, height: 900});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.screenshot({path: path.join(evidence, 'output-pages-narrow.png'), fullPage: true});
    report.checks.narrowLayout = true;
    report.result = 'passed';
  } catch(error) { report.result = 'failed'; report.failure = error.stack; throw error; }
  finally { fs.writeFileSync(path.join(evidence, 'browser-report.json'), JSON.stringify(report, null, 2)); await browser.close(); }
  console.log(JSON.stringify(report, null, 2));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
